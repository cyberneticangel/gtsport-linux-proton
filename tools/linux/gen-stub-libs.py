#!/usr/bin/env python3
"""Builds Linux versions of a RyGT release's logging stub libraries.

A release's libs/ folder has small placeholder libraries for PS4 system modules neither RyGT's
runtime nor shadGT implements. Most export the module's functions by NID, and a call logs
"[stub] <library> <NID>" to stderr once and returns 0 (libSceNpTrophy.prx); some return 0
without logging (libSceSsl2.prx); some export only ryty_stub_none, so that a library of that
name exists (libSceFreeTypeFull-PRX.prx).
They are Windows DLLs, so a native Linux build needs its own: this reads the NIDs each Windows
stub exports and compiles an ELF shared library with the same exports and behavior.

Usage: gen-stub-libs.py [--except <folder>] <release libs folder> <output folder> [library.prx ...]
Without library names, every placeholder in the folder is built: a small library that imports
only the C runtime, kernel32 and at most libc.prx. --except skips the libraries a folder (the
native build's libs) already has: some real runtime libraries are just as small.
Needs a C compiler (cc).
SPDX-License-Identifier: GPL-2.0-only
"""
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile

MAX_STUB_SIZE = 256 * 1024


def exported_names(path: pathlib.Path) -> list[str]:
    """Names in a PE file's export table."""
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError(f"{path} is not a PE file")
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    export_rva = struct.unpack_from("<I", data, pe + 24 + 112)[0]  # PE32+ data directory 0
    if export_rva == 0:
        return []
    table = pe + 24 + optional_size

    def offset(rva: int) -> int:
        for i in range(count):
            virtual_size, va, raw_size, raw = struct.unpack_from("<IIII", data, table + i * 40 + 8)
            if va <= rva < va + max(virtual_size, raw_size):
                return rva - va + raw
        raise ValueError(f"RVA {rva:#x} is in no section of {path}")

    directory = offset(export_rva)
    name_count, _, names_rva = struct.unpack_from("<III", data, directory + 24)
    names = []
    for i in range(name_count):
        name = offset(struct.unpack_from("<I", data, offset(names_rva) + 4 * i)[0])
        names.append(data[name:data.index(b"\0", name)].decode())
    return names


def imported_dlls(path: pathlib.Path) -> list[str]:
    """DLL names in a PE file's import table."""
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    import_rva = struct.unpack_from("<I", data, pe + 24 + 120)[0]  # PE32+ data directory 1
    table = pe + 24 + optional_size

    def offset(rva: int) -> int:
        for i in range(count):
            virtual_size, va, raw_size, raw = struct.unpack_from("<IIII", data, table + i * 40 + 8)
            if va <= rva < va + max(virtual_size, raw_size):
                return rva - va + raw
        raise ValueError(f"RVA {rva:#x} is in no section of {path}")

    dlls, descriptor = [], offset(import_rva)
    while (name_rva := struct.unpack_from("<I", data, descriptor + 12)[0]) != 0:
        name = offset(name_rva)
        dlls.append(data[name:data.index(b"\0", name)].decode())
        descriptor += 20
    return dlls


def is_stub(path: pathlib.Path) -> bool:
    if path.stat().st_size > MAX_STUB_SIZE:
        return False
    return all(d.lower() in ("kernel32.dll", "libc.prx") or d.lower().startswith("api-ms-win-crt-")
               for d in imported_dlls(path))


# Functions that block on the console: returning at once makes the game's polling loop spin a CPU
# core (GT Sport polls libSceUsbd's event handling). These wait as an idle USB stack would.
WAITING_STUBS = {
    # sceUsbdHandleEventsTimeout(const OrbisKernelTimeval* tv): up to the timeout (100 ms at most).
    "+wU6CGuZcWk": '''{
    struct { long long sec, usec; } const* tv = (const void*)a0;
    long long ns = tv ? tv->sec * 1000000000LL + tv->usec * 1000LL : 10000000LL;
    if (ns < 0) ns = 0;
    if (ns > 100000000LL) ns = 100000000LL;
    struct timespec t = { (time_t)(ns / 1000000000LL), (long)(ns % 1000000000LL) };
    nanosleep(&t, 0);
    return 0;
}''',
    # sceUsbdHandleEvents(void) and sceUsbdHandleEventsLocked(): block until an event; 100 ms.
    "EkqGLxWC-S0": "{ struct timespec t = {0, 100000000L}; nanosleep(&t, 0); return 0; }",
    "rt-WeUGibfg": "{ struct timespec t = {0, 100000000L}; nanosleep(&t, 0); return 0; }",
}


def c_source(library: str, nids: list[str], logs: bool) -> str:
    lines = [
        "// Generated by gen-stub-libs.py: logging stubs for " + library + ".",
        "#include <stdatomic.h>",
        "#include <stdio.h>",
        "#include <time.h>",
        "",
        f"static const char* const nids[{len(nids)}] = {{",
        *[f'    "{nid}",' for nid in nids],
        "};",
        f"static atomic_int noted[{len(nids)}];",
        "",
        "static void note(int index) {",
        "    if (" + ("1" if logs else "0") + " && atomic_exchange(&noted[index], 1) == 0) {",
        f'        fprintf(stderr, "[stub] {library} %s\\n", nids[index]);',
        "    }",
        "}",
        "",
    ]
    for index, nid in enumerate(nids):
        # NIDs contain '+' and '-', so the symbol name is given to the assembler, quoted.
        if nid in WAITING_STUBS:
            lines.append(f'__attribute__((visibility("default"))) long s{index}(const void* a0) __asm__("\\"{nid}\\"");')
            lines.append(f"long s{index}(const void* a0) {WAITING_STUBS[nid]}")
            continue
        lines.append(f'__attribute__((visibility("default"))) long s{index}(void) __asm__("\\"{nid}\\"");')
        lines.append(f"long s{index}(void) {{ note({index}); return 0; }}")
    return "\n".join(lines) + "\n"


def build(source_lib: pathlib.Path, output_dir: pathlib.Path, cc: str) -> int:
    library = source_lib.name.removesuffix(".prx")
    nids = exported_names(source_lib)
    if not nids or not all(re.fullmatch(r"[A-Za-z0-9+\-_]+", n) for n in nids):
        raise ValueError(f"{source_lib}: unexpected export names")
    with tempfile.TemporaryDirectory() as work:
        source = pathlib.Path(work) / (library + ".c")
        source.write_text(c_source(library, nids, b"[stub] " in source_lib.read_bytes()))
        subprocess.run([cc, "-O2", "-shared", "-fPIC", "-fvisibility=hidden", "-o",
                        str(output_dir / source_lib.name), str(source)], check=True)
    return len(nids)


def main() -> int:
    args = sys.argv[1:]
    skip = set()
    if args[:1] == ["--except"] and len(args) >= 2:
        skip = {p.name for p in pathlib.Path(args[1]).glob("*.prx")}
        args = args[2:]
    if len(args) < 2:
        print("usage: gen-stub-libs.py [--except <folder>] <release libs folder> <output folder> "
              "[library.prx ...]", file=sys.stderr)
        return 2
    libs, output = pathlib.Path(args[0]), pathlib.Path(args[1])
    cc = shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")
    if not cc:
        print("gen-stub-libs: no C compiler", file=sys.stderr)
        return 1
    output.mkdir(parents=True, exist_ok=True)
    names = args[2:]
    sources = [libs / n for n in names] if names else sorted(
        p for p in libs.glob("*.prx") if p.name not in skip and is_stub(p))
    for source in sources:
        print(f"{source.name}: {build(source, output, cc)} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
